import type { UppKey } from '../types/campaign';

export interface StatTarget {
  stat: UppKey;
  target: number;
}

export interface CareerAssignment {
  id: string;
  name: string;
  description: string;
  survival: StatTarget;
  advancement: StatTarget;
  specialistSkills: string[]; // 6 skills (1D6)
  ranks: Array<{ rank: number; title: string; bonusSkill?: string }>;
}

export interface CareerDef {
  id: string;
  name: string;
  summary: string;
  qualification: StatTarget | null; // null = auto-qualify (Drifter)
  isMilitary: boolean;
  commission?: StatTarget;
  officerRanks?: Array<{ rank: number; title: string; bonusSkill?: string }>;
  officerSkills?: string[];
  basicTrainingUsesSpecialist?: boolean; // Citizen & Drifter use Assignment Specialist skills
  serviceSkills: string[];
  personalDev: string[];
  advancedEdu: string[];
  advancedEduMinEdu: number;
  medicalCoverage: number; // % paid on injury (0, 50, 75, 100)
  mishaps: string[]; // 1D6 (index 0..5)
  events: string[]; // 2D6 (index 0..10 for rolls 2..12)
  cashTable: number[]; // 1D6 + optional +1 Gambling/Rank (7 entries)
  benefitsTable: string[]; // 7 entries
  assignments: CareerAssignment[];
}

export interface PreCareerDef {
  id: string;
  name: string;
  entry: StatTarget;
  graduation: StatTarget;
  honorsTarget: number;
  skillsOffered: string[];
  honorsBonus: string;
  autoQualifiesFor: string[];
}

export interface SkillPackageDef {
  id: string;
  name: string;
  description: string;
  skills: string[];
}

