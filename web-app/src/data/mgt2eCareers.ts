export function getCareerById(id: string): CareerDef | undefined {
  return MGT2E_CAREERS.find((c) => c.id === id);
}

/**
 * Returns the exact Basic Training skills granted when entering a career:
 * - First career (priorTerms === 0): ALL 6 Service Skills (or Assignment Specialist skills for Citizen/Drifter) at Level 0.
 * - Subsequent career: Player picks ONE skill from that same list at Level 0.
 */
export function getBasicTrainingPool(career: CareerDef, assignmentId: string): string[] {
  if (career.basicTrainingUsesSpecialist) {
    const asg = career.assignments.find((a) => a.id === assignmentId);
    if (asg) return asg.specialistSkills;
  }
  return career.serviceSkills;
}
